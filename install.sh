#!/usr/bin/env bash
# ==============================================================================
# NovaTunnel VPN - Automated Server Installation Script for Ubuntu / Debian
# ==============================================================================

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
BOLD='\033[1m'
NC='\033[0m'

echo -e "${CYAN}${BOLD}"
cat << "EOF"
  _   _                 _____                          _ 
 | \ | |               |_   _|                        | |
 |  \| | _____   ____ _  | |_   _ _ __  _ __   ___| |
 | . ` |/ _ \ \ / / _` | | | | | | '_ \| '_ \ / _ \ |
 | |\  | (_) \ V / (_| | | | |_| | | | | | | |  __/ |
 |_| \_|\___/ \_/ \__,_| |_|\__,_|_| |_|_| |_|\___|_|
                                                      
     Encrypted High-Performance TUN-Based VPN Server
EOF
echo -e "${NC}"

# Check for root privileges
if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}[!] Error: This script must be run as root (use sudo).${NC}"
    exit 1
fi

echo -e "${CYAN}[*] Step 1/6: Installing system prerequisites...${NC}"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y --no-install-recommends \
    python3 \
    python3-pip \
    python3-venv \
    iproute2 \
    iptables \
    curl \
    openssl \
    ca-certificates

echo -e "${CYAN}[*] Step 2/6: Setting up NovaTunnel directories & virtualenv...${NC}"
mkdir -p /etc/novatunnel /var/lib/novatunnel /opt/novatunnel

# Setup virtual environment in /opt/novatunnel/venv
python3 -m venv /opt/novatunnel/venv
/opt/novatunnel/venv/bin/pip install --upgrade pip setuptools wheel

# Install NovaTunnel from current directory or repository
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ -f "$SCRIPT_DIR/setup.py" ]; then
    echo -e "${CYAN}[*] Installing NovaTunnel from local source: $SCRIPT_DIR...${NC}"
    /opt/novatunnel/venv/bin/pip install -e "$SCRIPT_DIR"
else
    echo -e "${CYAN}[*] Installing NovaTunnel dependencies...${NC}"
    /opt/novatunnel/venv/bin/pip install cryptography flask click tomli tomli-w qrcode pillow
fi

# Symlink binaries to /usr/local/bin
ln -sf /opt/novatunnel/venv/bin/novatunnel-server /usr/local/bin/novatunnel-server
ln -sf /opt/novatunnel/venv/bin/novatunnel-client /usr/local/bin/novatunnel-client

echo -e "${CYAN}[*] Step 3/6: Generating server X25519 keys & credentials...${NC}"
SERVER_KEYS=$(/opt/novatunnel/venv/bin/python3 -c "
from novatunnel import crypto
priv, pub = crypto.generate_keypair()
print(f'{crypto.key_to_hex(priv)}:{crypto.key_to_hex(pub)}')
")

SERVER_PRIV_KEY=$(echo "$SERVER_KEYS" | cut -d':' -f1)
SERVER_PUB_KEY=$(echo "$SERVER_KEYS" | cut -d':' -f2)
DASHBOARD_SECRET=$(openssl rand -hex 32)
ADMIN_PASS=$(openssl rand -base64 12 | tr -dc 'a-zA-Z0-9' | head -c 12)

# Detect default physical interface and public IP
DEFAULT_IFACE=$(ip route show default | awk '/dev/ {print $5}' | head -n1)
PUBLIC_IP=$(curl -s4 https://api.ipify.org || echo "YOUR_SERVER_PUBLIC_IP")

CONFIG_FILE="/etc/novatunnel/server.toml"
if [ ! -f "$CONFIG_FILE" ]; then
    cat > "$CONFIG_FILE" << EOF
# NovaTunnel Server Configuration
# Generated by install.sh on $(date)

[server]
host = "0.0.0.0"
port = 51820
private_key = "${SERVER_PRIV_KEY}"
public_key = "${SERVER_PUB_KEY}"
vpn_subnet = "10.8.0.0/24"
server_vpn_ip = "10.8.0.1"
tun_name = "nova0"
mtu = 1420
dns = ["1.1.1.1", "8.8.8.8"]
max_peers = 50
peers_file = "/etc/novatunnel/peers.json"

# Disabled by default until secure HTTPS access is configured.
[dashboard]
enabled = false
host = "127.0.0.1"
port = 8080
secret_key = "${DASHBOARD_SECRET}"
username = "admin"
password = "${ADMIN_PASS}"
EOF
    chmod 600 "$CONFIG_FILE"
    echo -e "${GREEN}[+] Created server config at $CONFIG_FILE${NC}"
else
    echo -e "${YELLOW}[!] Existing configuration found at $CONFIG_FILE. Preserving it.${NC}"
fi

echo -e "${CYAN}[*] Step 4/6: Enabling IPv4 forwarding & kernel parameters...${NC}"
sysctl -w net.ipv4.ip_forward=1 > /dev/null
if ! grep -q "^net.ipv4.ip_forward=1" /etc/sysctl.conf; then
    echo "net.ipv4.ip_forward=1" >> /etc/sysctl.conf
fi

echo -e "${CYAN}[*] Step 5/6: Installing systemd service...${NC}"
cat > /etc/systemd/system/novatunnel-server.service << EOF
[Unit]
Description=NovaTunnel VPN Server Daemon
Documentation=https://github.com/novatunnel/novatunnel-vpn
After=network.target network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/local/bin/novatunnel-server start --config /etc/novatunnel/server.toml
Restart=always
RestartSec=5s
KillMode=process
CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_RAW CAP_NET_BIND_SERVICE
AmbientCapabilities=CAP_NET_ADMIN CAP_NET_RAW CAP_NET_BIND_SERVICE
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable --now novatunnel-server

echo -e "${CYAN}[*] Step 6/6: Verifying service status...${NC}"
sleep 2
if systemctl is-active --quiet novatunnel-server; then
    echo -e "${GREEN}${BOLD}[✓] NovaTunnel VPN Server is active and running!${NC}"
else
    echo -e "${YELLOW}[!] Service status check returned non-active. Check logs with: journalctl -u novatunnel-server -e${NC}"
fi

echo ""
echo -e "${GREEN}================================================================${NC}"
echo -e "${GREEN}${BOLD}             NovaTunnel VPN Server Setup Completed!             ${NC}"
echo -e "${GREEN}================================================================${NC}"
echo -e "${BOLD}Server Public Key:${NC}   ${CYAN}${SERVER_PUB_KEY}${NC}"
echo -e "${BOLD}Server IP:${NC}           ${PUBLIC_IP}"
echo -e "${BOLD}VPN Port:${NC}            UDP 51820"
echo -e "${BOLD}Dashboard URL:${NC}       ${CYAN}http://${PUBLIC_IP}:8080${NC}"
echo -e "${BOLD}Dashboard Username:${NC}  admin"
echo -e "${BOLD}Dashboard Password:${NC}  ${YELLOW}${ADMIN_PASS}${NC}"
echo -e "${GREEN}================================================================${NC}"
echo -e "Quick management commands:"
echo -e "  - Add client peer:     ${CYAN}novatunnel-server add-peer --name myphone --out client.toml${NC}"
echo -e "  - List connected peers: ${CYAN}novatunnel-server list-peers${NC}"
echo -e "  - View server logs:    ${CYAN}journalctl -u novatunnel-server -f${NC}"
echo ""
